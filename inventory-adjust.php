<?php
$is_ajax = !empty($_SERVER['HTTP_X_REQUESTED_WITH']) && strtolower($_SERVER['HTTP_X_REQUESTED_WITH']) === 'xmlhttprequest';

if ($is_ajax) {
    @ini_set('display_errors', 0);
    header('Content-Type: application/json');
    ob_start(); // Start buffering to catch and discard HTML header outputs
}

require_once 'header.php';
require_once 'auth_check.php';
require_permission('manage_inventory');

if ($is_ajax) {
    ob_end_clean(); // Wipe out the HTML generated by header.php completely
    ob_start();     // Start a clean buffer for our JSON output
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $product_id = (int)($_POST['product_id'] ?? 0);
    $warehouse_id = (int)($_POST['warehouse_id'] ?? 0);
    $quantity = (float)($_POST['quantity'] ?? 0);
    $notes = trim($_POST['notes'] ?? '');

    $warehouse = fetch_one("SELECT * FROM warehouses WHERE warehouse_id = ? AND tenant_id = ?", $warehouse_id, $current_user->tenant_id);

    $product = fetch_one(
        "SELECT p.*, u.is_decimal FROM products p
         LEFT JOIN units_of_measurement u ON u.unit_id = p.unit_id
         WHERE p.product_id = ? AND p.tenant_id = ?",
        $product_id, $current_user->tenant_id
    );

    $has_access = $warehouse && ($warehouse['location_type'] === 'godown' ? can('view_godown') || can('manage_godown') : store_is_accessible($warehouse_id, false));

    if (!$product) {
        $res = ['success' => false, 'message' => 'Product not found.'];
    } elseif (!$has_access) {
        $res = ['success' => false, 'message' => 'Please select an active warehouse or store you can access.'];
    } elseif ($product['is_service']) {
        $res = ['success' => false, 'message' => 'Services cannot have stock.'];
    } elseif (!$product['is_decimal'] && $quantity != floor($quantity)) {
        $res = ['success' => false, 'message' => 'This product uses whole units only.'];
    } elseif ($quantity <= 0) {
        $res = ['success' => false, 'message' => 'Quantity must be greater than zero.'];
    } else {
        $stock = fetch_one(
            "SELECT * FROM inventory_stock WHERE product_id = ? AND warehouse_id = ? AND tenant_id = ?",
            $product_id, $warehouse_id, $current_user->tenant_id
        );
        $conn->begin_transaction();
        try {
            $type = 'restock';
            if ($stock) {
                $new = (float)$stock['quantity'] + $quantity;
                $stmt = $conn->prepare(
                    "UPDATE inventory_stock SET quantity = ?, last_counted_at = CURRENT_TIMESTAMP
                     WHERE stock_id = ? AND tenant_id = ?"
                );
                $stmt->bind_param('dii', $new, $stock['stock_id'], $current_user->tenant_id);
                $stmt->execute();
                $stmt->close();
            } else {
                $stmt = $conn->prepare(
                    "INSERT INTO inventory_stock (tenant_id, product_id, warehouse_id, quantity, reorder_level)
                     VALUES (?, ?, ?, ?, ?)"
                );
                $stmt->bind_param('iiidd', $current_user->tenant_id, $product_id, $warehouse_id, $quantity, $product['min_stock_level']);
                $stmt->execute();
                $stmt->close();
            }
            $stmt = $conn->prepare(
                "INSERT INTO inventory_movements (tenant_id, product_id, warehouse_id, movement_type, quantity, created_by, notes)
                 VALUES (?, ?, ?, ?, ?, ?, ?)"
            );
            $stmt->bind_param('iiisdis', $current_user->tenant_id, $product_id, $warehouse_id, $type, $quantity, $current_user->user_id, $notes);
            $stmt->execute();
            $stmt->close();
            
            $conn->commit();
            $res = ['success' => true, 'message' => 'Stock updated successfully.'];
        } catch (Exception $ex) {
            $conn->rollback();
            $res = ['success' => false, 'message' => 'Update failed: ' . $ex->getMessage()];
        }
    }

    if ($is_ajax) {
        if (ob_get_length()) ob_clean();
        echo json_encode($res);
        exit;
    }
    $msg = [$res['success'] ? 'success' : 'danger', $res['message']];
}

if ($is_ajax) {
    if (ob_get_length()) ob_clean();
    echo json_encode(['success' => false, 'message' => 'Invalid request method.']);
    exit;
}

// Fallback for direct non-AJAX browser access
$prefill_product = (int)($_GET['product'] ?? 0);
$prefill_warehouse = (int)($_GET['warehouse'] ?? 0);
$products = fetch_all("SELECT product_id, code, name, is_service FROM products WHERE tenant_id = ? AND is_active = 1 ORDER BY name", $current_user->tenant_id);
$warehouses = accessible_stores(null, false);

require_once 'navbar.php';
require_once 'sidebar.php';
?>
<div class="page-head">
    <div>
        <h1 class="page-title">Adjust / Restock</h1>
        <div class="page-sub">Add stock to a product in a warehouse.</div>
    </div>
    <a href="inventory.php" class="btn btn-light"><i class="fa fa-arrow-left mr-1"></i> Back to Inventory</a>
</div>

<?php if (!empty($msg)): ?>
    <div class="alert alert-<?php echo e($msg[0]); ?>"><?php echo e($msg[1]); ?></div>
<?php endif; ?>

<div class="row">
    <div class="col-lg-6">
        <div class="card">
            <div class="card-body">
                <form method="POST" action="inventory-adjust.php">
                    <div class="form-group">
                        <label>Product <span class="text-danger">*</span></label>
                        <select name="product_id" class="form-control" required>
                            <option value="">— Select Product —</option>
                            <?php foreach ($products as $p): ?>
                                <option value="<?php echo $p['product_id']; ?>" <?php echo $prefill_product === (int)$p['product_id'] ? 'selected' : ''; ?>><?php echo e($p['name'] . ' (' . $p['code'] . ')'); ?></option>
                            <?php endforeach; ?>
                        </select>
                    </div>
                    <div class="form-group">
                        <label>Store / Warehouse <span class="text-danger">*</span></label>
                        <select name="warehouse_id" class="form-control" required>
                            <?php foreach ($warehouses as $w): ?>
                                <option value="<?php echo $w['warehouse_id']; ?>" <?php echo $prefill_warehouse === (int)$w['warehouse_id'] ? 'selected' : ''; ?>><?php echo e(store_label($w)); ?></option>
                            <?php endforeach; ?>
                        </select>
                    </div>
                    <div class="form-group">
                        <label>Quantity to Add <span class="text-danger">*</span></label>
                        <input type="number" name="quantity" class="form-control" step="0.01" min="0.01" required>
                    </div>
                    <div class="form-group">
                        <label>Notes</label>
                        <textarea name="notes" class="form-control" rows="2" placeholder="e.g. Supplier delivery"></textarea>
                    </div>
                    <button type="submit" class="btn btn-primary"><i class="fa fa-check mr-1"></i> Save Stock</button>
                </form>
            </div>
        </div>
    </div>
</div>
